import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import type { LocalHttpSmokeResult } from "./smokeLocalHttpCore.js";
import { redactRemoteUrl } from "./smokeRemoteHttpCore.js";
import { evidenceTextSafetyProblem } from "./v1EvidenceSafety.js";

export interface WriteLocalHttpEvidenceOptions {
  readonly cwd: string;
  readonly artifact: string;
  readonly result: LocalHttpSmokeResult;
  readonly verifiedAt?: string | undefined;
}

export interface WriteLocalHttpEvidenceResult {
  readonly artifact: string;
  readonly path: string;
}

export function writeLocalHttpEvidenceArtifact(
  options: WriteLocalHttpEvidenceOptions,
): WriteLocalHttpEvidenceResult {
  const { artifact, path } = resolveProjectArtifact(
    options.cwd,
    options.artifact,
  );
  const markdown = renderLocalHttpEvidenceArtifact(
    options.result,
    options.verifiedAt ?? new Date().toISOString(),
  );
  const safetyProblem = evidenceTextSafetyProblem(
    `artifact ${artifact}`,
    markdown,
  );
  if (safetyProblem) {
    throw new Error(safetyProblem);
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, markdown);

  return {
    artifact,
    path,
  };
}

