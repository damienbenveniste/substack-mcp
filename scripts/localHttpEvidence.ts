function formatInspectorArgs(args: readonly string[]): string[] {
  return args.map((arg) => {
    try {
      const url = new URL(arg);
      return redactRemoteUrl(url);
    } catch {
      return arg;
    }
  });
}

function resolveProjectArtifact(
  cwd: string,
  value: string,
): { readonly artifact: string; readonly path: string } {
  const root = resolve(cwd);
  const path = resolve(root, value);
  const artifact = relative(root, path);
  if (artifact === "" || artifact.startsWith("..") || isAbsolute(artifact)) {
    throw new Error(
      "V1 local HTTP evidence artifact must stay inside the project directory.",
    );
  }

  return { artifact, path };
}
