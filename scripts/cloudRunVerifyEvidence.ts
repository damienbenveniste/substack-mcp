function cloudRunVerifyEvidenceCommand(
  report: CloudRunVerifyReport,
  artifact: string,
): string {
  return [
    "npm run cloud-run:verify --",
    "--service-json",
    ".data/cloud-run-service.json",
    ...(report.auth_mode === "static_bearer"
      ? []
      : ["--auth-mode", shellArg(report.auth_mode)]),
    ...expectedCheckValueArgs(report, "service_account", {
      expectedPrefix: "",
      flag: "--service-account-email",
      skipExpected: "configured service account",
    }),
    ...expectedCheckValueArgs(report, "env_substack_publication_url", {
      expectedPrefix: "SUBSTACK_PUBLICATION_URL=",
      flag: "--publication-url",
    }),
    ...expectedCheckValueArgs(report, "env_substack_user_id", {
      expectedPrefix: "SUBSTACK_USER_ID=",
      flag: "--user-id",
    }),
    ...expectedCheckValueArgs(report, "env_max_body_bytes", {
      expectedPrefix: "MAX_BODY_BYTES=",
      flag: "--max-body-bytes",
    }),
    ...expectedCheckValueArgs(report, "env_max_image_bytes", {
      expectedPrefix: "MAX_IMAGE_BYTES=",
      flag: "--max-image-bytes",
    }),
    ...expectedCheckValueArgs(report, "env_substack_request_timeout_ms", {
      expectedPrefix: "SUBSTACK_REQUEST_TIMEOUT_MS=",
      flag: "--substack-request-timeout-ms",
    }),
    ...expectedCheckValueArgs(report, "env_confirmation_token_ttl_seconds", {
      expectedPrefix: "CONFIRMATION_TOKEN_TTL_SECONDS=",
      flag: "--confirmation-token-ttl-seconds",
    }),
    ...expectedCheckValueArgs(report, "env_mcp_public_base_url", {
      expectedPrefix: "MCP_PUBLIC_BASE_URL=",
      flag: "--public-base-url",
    }),
    ...expectedCheckValueArgs(report, "env_oauth_authorization_server_url", {
      expectedPrefix: "OAUTH_AUTHORIZATION_SERVER_URL=",
      flag: "--oauth-authorization-server-url",
    }),
    ...expectedCheckValueArgs(report, "env_oauth_jwks_url", {
      expectedPrefix: "OAUTH_JWKS_URL=",
      flag: "--oauth-jwks-url",
    }),
    ...expectedCheckValueArgs(report, "env_oauth_resource_documentation_url", {
      expectedPrefix: "OAUTH_RESOURCE_DOCUMENTATION_URL=",
      flag: "--oauth-resource-documentation-url",
    }),
    ...expectedCheckValueArgs(report, "env_oauth_jwt_algorithms", {
      expectedPrefix: "OAUTH_JWT_ALGORITHMS=",
      flag: "--oauth-jwt-algorithms",
    }),
    "--evidence-artifact",
    shellArg(artifact),
  ].join(" ");
}

function expectedCheckValueArgs(
  report: CloudRunVerifyReport,
  checkId: string,
  options: {
    readonly expectedPrefix: string;
    readonly expectedSuffix?: string | undefined;
    readonly flag: string;
    readonly skipExpected?: string | undefined;
  },
): string[] {
  const expected = report.checks.find(
    (entry) => entry.id === checkId,
  )?.expected;
  if (!expected || expected === options.skipExpected) {
    return [];
  }

  if (
    !expected.startsWith(options.expectedPrefix) ||
    (options.expectedSuffix !== undefined &&
      !expected.endsWith(options.expectedSuffix))
  ) {
    return [];
  }

  const value = expected.slice(
    options.expectedPrefix.length,
    options.expectedSuffix === undefined
      ? expected.length
      : -options.expectedSuffix.length,
  );

  return value ? [options.flag, shellArg(value)] : [];
}

function remoteSmokeEvidenceAction(report: CloudRunVerifyReport): string {
  const mcpUrl = report.service_url
    ? `${report.service_url.replace(/\/+$/u, "")}/mcp`
    : "the deployed service MCP URL";

  switch (report.auth_mode) {
    case "noauth":
      return report.service_url
        ? `npm run smoke:remote-noauth -- --url ${shellArg(mcpUrl)}`
        : "run the noauth remote smoke against the deployed service MCP URL";
    case "oauth":
      return `run the OAuth remote smoke against ${mcpUrl} with a real access token`;
    case "static_bearer":
      return report.service_url
        ? `npm run smoke:remote -- --url ${shellArg(mcpUrl)}`
        : "run the static-bearer remote smoke against the deployed service MCP URL";
  }
}

function safeEvidenceDetail(value: string): string {
  return value.replace(
    /\b(SUBSTACK_SESSION_TOKEN|PREVIEW_TOKEN_SECRET|MCP_BEARER_TOKEN|MCP_PATH_SECRET)=/g,
    "$1 reference ",
  );
}

function resolveProjectArtifact(
  cwd: string,
  value: string,
): { readonly artifact: string; readonly path: string } {
  const root = resolve(cwd);
  const path = resolve(root, value);
  const artifact = relative(root, path);
  if (artifact === "" || artifact.startsWith("..") || isAbsolute(artifact)) {
    throw new Error(
      "V1 Cloud Run verify evidence artifact must stay inside the project directory.",
    );
  }

  return { artifact, path };
}
