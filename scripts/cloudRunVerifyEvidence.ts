import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";

import type { CloudRunVerifyReport } from "./cloudRunVerifyCore.js";
import { evidenceTextSafetyProblem } from "./v1EvidenceSafety.js";
import { formatV1RecordCommand, shellArg } from "./v1RecordCommandFormat.js";

const DEFAULT_GATE_12_ARTIFACT = ".data/v1/gate-12-cloud-run-deployment.md";

export interface WriteCloudRunVerifyEvidenceOptions {
  readonly cwd: string;
  readonly artifact: string;
  readonly report: CloudRunVerifyReport;
  readonly verifiedAt?: string | undefined;
}

export interface WriteCloudRunVerifyEvidenceResult {
  readonly artifact: string;
  readonly path: string;
}

export function writeCloudRunVerifyEvidenceArtifact(
  options: WriteCloudRunVerifyEvidenceOptions,
): WriteCloudRunVerifyEvidenceResult {
  const { artifact, path } = resolveProjectArtifact(
    options.cwd,
    options.artifact,
  );
  const markdown = renderCloudRunVerifyEvidenceArtifact(
    options.report,
    options.verifiedAt ?? new Date().toISOString(),
    artifact,
  );
  const safetyProblem = evidenceTextSafetyProblem(
    `artifact ${artifact}`,
    markdown,
  );
  if (safetyProblem) {
    throw new Error(safetyProblem);
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, markdown);

  return {
    artifact,
    path,
  };
}

