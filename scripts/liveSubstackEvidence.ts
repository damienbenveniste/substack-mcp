function richDraftEvidenceCommand(
  liveCommand: string,
  fixtureDirArg: string | undefined,
): string {
  return [
    fixtureStatusCommand(fixtureDirArg, true),
    fixtureCompatibilityTestCommand(fixtureDirArg),
    liveCommand,
  ].join("; ");
}

function liveGateArtifacts(
  artifact: string | undefined,
  allArtifacts: readonly string[] | undefined,
): LiveGateArtifacts {
  if (allArtifacts && allArtifacts.length > 1) {
    return liveGateArtifactsFromList(allArtifacts);
  }

  if (!artifact) {
    return DEFAULT_GATE_ARTIFACTS;
  }

  return {
    7: artifact,
    8: artifact,
    9: artifact,
  };
}

function liveGateArtifactsFromList(
  artifacts: readonly string[],
): LiveGateArtifacts {
  const mapped: Partial<LiveGateArtifacts> = {};
  const unassigned: string[] = [];
  for (const artifact of artifacts) {
    const gateId = liveGateIdFromArtifact(artifact);
    if (gateId) {
      mapped[gateId] = artifact;
    } else {
      unassigned.push(artifact);
    }
  }

  const missingGateIds = ([7, 8, 9] as const).filter(
    (gateId) => mapped[gateId] === undefined,
  );
  for (const [index, gateId] of missingGateIds.entries()) {
    const artifact = unassigned[index];
    if (artifact) {
      mapped[gateId] = artifact;
    }
  }

  return {
    7: mapped[7] ?? DEFAULT_GATE_ARTIFACTS[7],
    8: mapped[8] ?? DEFAULT_GATE_ARTIFACTS[8],
    9: mapped[9] ?? DEFAULT_GATE_ARTIFACTS[9],
  };
}

function liveGateIdFromArtifact(artifact: string): 7 | 8 | 9 | undefined {
  const match = artifact.match(/(?:^|[/-])gate-0?(7|8|9)(?:[-.]|$)/u);
  if (!match) {
    return undefined;
  }

  return Number(match[1]) as 7 | 8 | 9;
}

function liveSubstackCommand(
  artifact: string | undefined,
  allArtifacts: readonly string[] | undefined,
): string {
  if (allArtifacts && allArtifacts.length > 1) {
    return `V1_LIVE_SUBSTACK_EVIDENCE_ARTIFACTS=${allArtifacts
      .map(shellArg)
      .join(",")} RUN_LIVE_SUBSTACK_TESTS=1 npm run test:live`;
  }

  if (artifact) {
    return `V1_LIVE_SUBSTACK_EVIDENCE_ARTIFACT=${shellArg(artifact)} RUN_LIVE_SUBSTACK_TESTS=1 npm run test:live`;
  }

  return `V1_LIVE_SUBSTACK_EVIDENCE_ARTIFACTS=${Object.values(
    DEFAULT_GATE_ARTIFACTS,
  ).join(",")} RUN_LIVE_SUBSTACK_TESTS=1 npm run test:live`;
}

function splitArtifactList(value: string | undefined): readonly string[] {
  return value
    ? value
        .split(/[,\n]/)
        .map((artifact) => artifact.trim())
        .filter((artifact) => artifact.length > 0)
    : [];
}

function checklistLine(checked: boolean, label: string): string {
  return `- [${checked ? "x" : " "}] ${label}`;
}

function resolveProjectArtifact(
  cwd: string,
  value: string,
): { readonly artifact: string; readonly path: string } {
  const root = resolve(cwd);
  const path = resolve(root, value);
  const artifact = relative(root, path);
  if (artifact === "" || artifact.startsWith("..") || isAbsolute(artifact)) {
    throw new Error(
      "V1 live evidence artifact must stay inside the project directory.",
    );
  }

  return { artifact, path };
}

export function resolveLiveSubstackEvidenceArtifact(
  cwd: string,
  value: string,
): { readonly artifact: string; readonly path: string } {
  return resolveProjectArtifact(cwd, value);
}

function resolveProjectFixtureDirArg(
  cwd: string,
  value: string | undefined,
): string | undefined {
  const trimmed = value?.trim();
  if (!trimmed) {
    return undefined;
  }
  if (/[\r\n]/u.test(trimmed)) {
    throw new Error(
      "V1 live fixture directory must be a single project-local path.",
    );
  }

  const root = resolve(cwd);
  const path = resolve(root, trimmed);
  if (path === resolve(root, "fixtures", "substack")) {
    return undefined;
  }

  const fixtureDir = relative(root, path);
  if (
    fixtureDir === "" ||
    fixtureDir.startsWith("..") ||
    isAbsolute(fixtureDir)
  ) {
    throw new Error(
      "V1 live fixture directory must stay inside the project directory.",
    );
  }

  return fixtureDir;
}
