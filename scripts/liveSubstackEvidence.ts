import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import {
  fixtureCompatibilityTestCommand,
  fixtureStatusCommand,
} from "./fixtureStatusCore.js";
import { evidenceTextSafetyProblem } from "./v1EvidenceSafety.js";
import { formatV1RecordCommand, shellArg } from "./v1RecordCommandFormat.js";

type LiveGateArtifacts = Record<7 | 8 | 9, string>;

const DEFAULT_GATE_ARTIFACTS: LiveGateArtifacts = {
  7: ".data/v1/gate-07-rich-draft-live-fixtures.md",
  8: ".data/v1/gate-08-update-draft-live.md",
  9: ".data/v1/gate-09-read-drafts-live.md",
};

export interface LiveSubstackEvidence {
  readonly verified_at: string;
  readonly draft_id: number;
  readonly draft_url?: string | undefined;
  readonly created_title: string;
  readonly updated_title: string;
  readonly image_upload_verified: boolean;
  readonly create_verified: boolean;
  readonly list_verified: boolean;
  readonly get_verified: boolean;
  readonly update_verified: boolean;
  readonly post_update_get_verified: boolean;
}

export interface WriteLiveSubstackEvidenceOptions {
  readonly cwd: string;
  readonly artifact: string;
  readonly allArtifacts?: readonly string[] | undefined;
  readonly fixtureDir?: string | undefined;
  readonly evidence: LiveSubstackEvidence;
}

export interface WriteLiveSubstackEvidenceArtifactsOptions {
  readonly cwd: string;
  readonly artifacts: readonly string[];
  readonly fixtureDir?: string | undefined;
  readonly evidence: LiveSubstackEvidence;
}

export interface WriteLiveSubstackEvidenceResult {
  readonly artifact: string;
  readonly path: string;
}

export function parseLiveSubstackEvidenceArtifacts(
  env: Partial<Record<string, string | undefined>> = process.env,
): readonly string[] {
  const artifacts = [
    ...splitArtifactList(env.V1_LIVE_SUBSTACK_EVIDENCE_ARTIFACT),
    ...splitArtifactList(env.V1_LIVE_SUBSTACK_EVIDENCE_ARTIFACTS),
  ];
  return [...new Set(artifacts)];
}

export function writeLiveSubstackEvidenceArtifacts(
  options: WriteLiveSubstackEvidenceArtifactsOptions,
): readonly WriteLiveSubstackEvidenceResult[] {
  return options.artifacts.map((artifact) =>
    writeLiveSubstackEvidenceArtifact({
      cwd: options.cwd,
      artifact,
      allArtifacts: options.artifacts,
      fixtureDir: options.fixtureDir,
      evidence: options.evidence,
    }),
  );
}

export function writeLiveSubstackEvidenceArtifact(
  options: WriteLiveSubstackEvidenceOptions,
): WriteLiveSubstackEvidenceResult {
  const { artifact, path } = resolveLiveSubstackEvidenceArtifact(
    options.cwd,
    options.artifact,
  );
  const fixtureDirArg = resolveProjectFixtureDirArg(
    options.cwd,
    options.fixtureDir,
  );
  const markdown = renderLiveSubstackEvidenceArtifact(
    options.evidence,
    artifact,
    options.allArtifacts,
    fixtureDirArg,
  );
  const safetyProblem = evidenceTextSafetyProblem(
    `artifact ${artifact}`,
    markdown,
  );
  if (safetyProblem) {
    throw new Error(safetyProblem);
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, markdown);
  return {
    artifact,
    path,
  };
}

